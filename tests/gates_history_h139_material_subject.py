"""2026-10-31 コーポレートの記事が一次性78点で止まった。材料の判定（material.hits）は「題を分ける語のどれか1つ」を
含む文を数えていたので、2語の題の片方だけに当たる周辺の数字（「仕訳の誤りの直し約90件」「インボイス対応22社」）で
「材料あり」と数え、主題そのものの数字が無いまま書かせていた。運用者「マジで精度上げてちゃんと基準になるように」。

一次性の80点は「自社の経験や数字が2か所以上・うち1つは母数つき」。そこで材料の文として数えるのは、
題の中身の語（サービス名・探し方の語を除く）を全部、同じ文の近い所（40字以内）に含み、母数つきの数字（何社・何件・何名…）がある文だけにする。
材料の依頼（material.ask）も、汎用の「実際にあったことを2〜3件」だけでなく、記事の見出しと採点者の指摘から
主題の数字を聞く（事実は作らない。聞くだけ）。
"""
import sys
import tempfile
from pathlib import Path

from test_gates import check, ROOT

sys.path.insert(0, str(ROOT / "scripts"))


POOL = ["見積書 値引き", "見積書 書き方", "値引き 交渉", "見積書 有効期限", "納品書 書き方", "zz 外注 費用"]


def test_material_needs_subject_and_base_number():
    import material as M
    print("\n■ 材料の文は、題の語2つを同じ文に含み、母数つきの数字があるものだけを数える（周辺の数字で「あり」にしない）")
    neighbors = ["2023年4月から見積書の作成代行を18社で担当しています",
                 "値引きの相談は年間約40件ありました",
                 "請け負った12社のうち、見積書を電子化したのは5社です"]
    check("悪い例: 題の語の片方ずつにしか当たらない周辺の数字は材料ではない",
          (M.hits("見積書 値引き", neighbors, POOL), M.hits("見積書 値引き", neighbors)), (0, 0))
    good = neighbors + ["2024年に受けた見積書120件のうち、値引きの理由は端数の切り捨てが45件、まとめ買いが30件でした"]
    check("良い例: 題の語2つと母数つきの数字がそろった文は材料", M.hits("見積書 値引き", good, POOL), 1)
    check("題の語が離れた内訳の文（別々の話を並べただけ）は数えない",
          M.hits("見積書 値引き", ["見積書の作成代行を担当した33社の内訳は、小売7社、飲食6社、建設5社、医療4社、士業2社、IT・Web2社、値引きの多い卸3社です"], POOL), 0)
    check("材料の文が複数の文でも、同じ文の中で見る",
          M.hits("見積書 値引き", ["見積書の作成を18社で代行しています。値引きの相談は年間約40件です。"], POOL), 0)
    check("題の語2つがあっても数字の無い文は数えない",
          M.hits("見積書 値引き", ["見積書の値引きはよく相談されます"], POOL), 0)
    check("1語の題（多くの題に出る語を除いて1語）は、その語と母数つきの数字で数える",
          (M.hits("zz 外注", ["外注を9社のうち4社で見直しました"], POOL + ["zz 料金", "zz 事例", "zz 比較"]),
           M.hits("zz 外注", ["zz の記事を9社で書きました"], POOL + ["zz 料金", "zz 事例", "zz 比較"])), (1, 0))


def test_material_ask_names_the_subject():
    import material as M
    print("\n■ 材料の依頼は、主題の数字と見出しと採点者の指摘を名指しで聞く（汎用の質問だけにしない。事実は作らない）")
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "material_requests.json"
        weak = ["主題の値引きそのものに関する当社の実測がない。現場の具体例が薄い。",
                "仕訳例は公開情報の整理にとどまる。",
                "値引きの理由別の件数や、端数が占める割合などの数字が無い。"]
        M.ask("zz-site", "zz-a", "見積書 値引き", weak, path=p,
              heads=["値引きの理由と仕訳", "端数の切り捨てはどう扱うか", "まとめ"])
        import json
        q = json.loads(p.read_text(encoding="utf-8"))["zz-site"]["zz-a"]["questions"]
    text = "\n".join(q)
    check("主題そのものの母数つきの数字を聞く", ("「見積書 値引き」そのもの" in text, "何件のうち" in text), (True, True))
    check("採点者が無いと言った数字をそのまま聞く", "値引きの理由別の件数" in text, True)
    check("見出しごとに実例を聞く（まとめ・よくある質問は聞かない）",
          ("値引きの理由と仕訳" in text, "端数の切り捨てはどう扱うか" in text, "「まとめ」" in text), (True, True, False))
    check("質問は5つまで", len(q) <= 5, True)
