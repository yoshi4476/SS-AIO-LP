def fill(path, overview, rows, note):
    from openpyxl import load_workbook
    from openpyxl.styles import Font
    wb = load_workbook(BASE)
    w = wb["概要"]
    for r in w.iter_rows(min_row=2):
        key = str(r[0].value or "").strip()
        if key in overview:
            r[1].value = overview[key]
    d = wb["データ"]
    # 3行目以降（例の下）に差し込む。例の行は残して見本にする
    for i, row in enumerate(rows, 3):
        for j, v in enumerate(row, 1):
            d.cell(row=i, column=j, value=v)
    ws = wb["書き方"]
    ws.cell(row=ws.max_row + 2, column=1, value="このシートについて: " + note).font = Font(bold=True)
    wb.save(path)


def main():
    if not BASE.is_file():
        print("  雛形がありません。先に python scripts/data_intake.py --sheet を実行してください")
        return 1
    for name, ov, rows, note in PLANS:
        p = OUT / name
        fill(p, ov, rows, note)
        print(f"  作成: intake/{name}")
    print(f"{chr(10)}  数字だけを埋めて intake/ に置き、"
          "python scripts/intake_watch.py --apply で公開されます")
    return 0


