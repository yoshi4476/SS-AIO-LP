# -*- coding: utf-8 -*-
"""検索語を「開かないと済まない語」かどうかで採点する。

順位が同じでもクリック率は5倍違った。28日の実測で、AI集客ラボの
記事は6〜10位でCTR 1.04%、補助金サポートは同じ帯で2.80%だった。
差は順位ではなく、検索語の性質にあった。

  弱い語: 例文・診断・とは・一覧
    → 検索結果に答えが1つ出た時点で用が済む。開く理由が無い。
    実際「口コミ 返信 例文 医療」は8.5位で88表示・0クリックだった。

  強い語: 書き方・不採択理由・対象条件・トラブル
    → 開かないと手続きが進まない、判断できない。
    「AI導入補助金の不採択理由」は5.5位で45表示・4クリック（8.9%）。

使い方:
    python scripts/kw_intent.py "口コミ 返信 例文 医療" "ai補助金 不採択理由"
    from kw_intent import score        # 他のスクリプトから
"""
import re
import sys

# 開かないと済まない語。数字が大きいほどクリックが必要になる
STRONG = [
    (3, r"書き方|記入例|作り方|手順|ステップ|進め方|申請方法"),
    (3, r"不採択|落ちる|審査に通らない|断られ|却下|失敗|トラブル|クレーム"),
    (3, r"必要書類|添付書類|提出書類|様式|期限|締切|いつまで"),
    (2, r"対象|条件|要件|基準|資格|使えるか|できるか|可能か|該当"),
    (2, r"注意点|やってはいけない|(?<![a-z])ng(?![a-z])|落とし穴|リスク|違反"),  # 照合前に lower() するため小文字で書く
    (2, r"選び方|比較|違い|どっち|どちら"),
    (2, r"費用|相場|いくら|料金|内訳|見積"),
    (1, r"できない|進まない|表示されない|反映されない|エラー"),
    (1, r"後悔|やめた|評判|口コミは"),
]

# 検索結果で用が済みやすい語。開く理由をこちらで作らないと読まれない
WEAK = [
    (-3, r"例文|テンプレート|ひな形|文例|定型文"),
    (-2, r"とは$|とは\s|意味|読み方|(?<![戦攻省])略"),  # 戦略・攻略は買い手の語
    (-2, r"一覧|まとめ$|リスト$"),
    (-2, r"診断|チェック$|チェックツール"),
    (-1, r"おすすめ$|人気$|ランキング"),
]


def _label(pat):
    """理由の表示用。先読み・後読みは語ではないので除く（kw_guard・月次レポートの表に「(?<」が出ていた）"""
    return re.sub(r"[|$\\s]", "/", re.sub(r"\(\?<?[!=][^)]*\)", "", pat))[:16]


# 外注・比較を考えている人の語。検索数は少ないが、問い合わせに近い
BUYER = re.compile(r"代行|外注|委託|依頼|会社|業者|サービス|比較|おすすめ|選び方|"
                   r"費用|料金|相場|見積|導入|申請 代行|コンサル|支援|丸投げ")
# 見込み客でない検索。ラッコのLSIは重要度highで返すが、読者は顧客ではない
NOT_BUYER = ("求人", "転職", "副業", "在宅ワーク", "フリーランス", "資格", "儲かる",
             "年収", "給料", "時給", "未経験", "パート", "バイト", "独立", "開業 資金",
             "面接", "志望動機", "学校", "スクール", "講座", "検定", "試験")
# 業種の名前に入る「会社」は依頼先を探す語ではない（不動産会社 ホームページ など）
_TRADE_COMPANY = re.compile(r"(不動産|リフォーム|建設|建築|住宅|工務|管理|保険|運送)会社")
# 自分でやる人の語。「導入事例 書き方」「相場記事 の作り方」は依頼先を探していない
_SELF_SERVE = re.compile(r"書き方|作り方|やり方|自分で|比較記事|相場記事|導入事例")


def is_buyer(kw):
    """依頼先を探している人の語か"""
    low = str(kw).lower()
    if any(t in low for t in NOT_BUYER) or _SELF_SERVE.search(low):
        return False
    return bool(BUYER.search(_TRADE_COMPANY.sub("", low)))


def score(kw):
    """(点数, 理由) を返す。1以上なら開く理由がある語とみなす"""
    s = str(kw).lower()
    pts, why = 0, []
    for w, pat in STRONG:
        if re.search(pat, s):
            pts += w
            why.append("+" + _label(pat))
    for w, pat in WEAK:
        if re.search(pat, s):
            pts += w
            why.append(_label(pat))
    # 語数が多いほど具体的で、答えが1文で済みにくい
    if len(re.split(r"[\s　]+", s.strip())) >= 3:
        pts += 1
        why.append("+具体的")
    return pts, "・".join(why[:4]) or "手がかりなし"


def verdict(kw):
    p, why = score(kw)
    if p >= 2:
        return "強", p, why
    if p >= 0:
        return "並", p, why
    return "弱", p, why


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 0
    print("%-4s %4s  %-34s %s" % ("判定", "点", "検索語", "理由"))
    for kw in sys.argv[1:]:
        v, p, why = verdict(kw)
        print("%-4s %4d  %-34s %s" % (v, p, kw[:34], why))
    return 0


if __name__ == "__main__":
    sys.exit(main())
