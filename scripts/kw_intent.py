# -*- coding: utf-8 -*-
"""検索語を「開かないと済まない語」かどうかで採点する。

順位が同じでもクリック率は5倍違った。28日の実測で、AI集客ラボの
記事は6〜10位でCTR 1.04%、補助金サポートは同じ帯で2.80%だった。
差は順位ではなく、検索語の性質にあった。

  弱い語: 例文・診断・とは・一覧
    → 検索結果に答えが1つ出た時点で用が済む。開く理由が無い。
    実際「口コミ 返信 例文 医療」は8.5位で88表示・0クリックだった。

  強い語: 書き方・不採択理由・対象条件・トラブル
    → 開かないと手続きが進まない、判断できない。
    「AI導入補助金の不採択理由」は5.5位で45表示・4クリック（8.9%）。

使い方:
    python scripts/kw_intent.py "口コミ 返信 例文 医療" "ai補助金 不採択理由"
    from kw_intent import score        # 他のスクリプトから
"""
import re
import sys

# 開かないと済まない語。数字が大きいほどクリックが必要になる
STRONG = [
    (3, r"書き方|記入例|作り方|手順|ステップ|進め方|申請方法"),
    (3, r"不採択|落ちる|審査に通らない|断られ|却下|失敗|トラブル|クレーム"),
    (3, r"必要書類|添付書類|提出書類|様式|期限|締切|いつまで"),
    (2, r"対象|条件|要件|基準|資格|使えるか|できるか|可能か|該当"),
    (2, r"注意点|やってはいけない|NG|落とし穴|リスク|違反"),
    (2, r"選び方|比較|違い|どっち|どちら"),
    (2, r"費用|相場|いくら|料金|内訳|見積"),
    (1, r"できない|進まない|表示されない|反映されない|エラー"),
    (1, r"後悔|やめた|評判|口コミは"),
]

# 検索結果で用が済みやすい語。開く理由をこちらで作らないと読まれない
WEAK = [
    (-3, r"例文|テンプレート|ひな形|文例|定型文"),
    (-2, r"とは$|とは\s|意味|読み方|略"),
    (-2, r"一覧|まとめ$|リスト$"),
    (-2, r"診断|チェック$|チェックツール"),
    (-1, r"おすすめ$|人気$|ランキング"),
]


def score(kw):
    """(点数, 理由) を返す。1以上なら開く理由がある語とみなす"""
    s = str(kw).lower()
    pts, why = 0, []
    for w, pat in STRONG:
        if re.search(pat, s):
            pts += w
            why.append("+" + re.sub(r"[|$\\s]", "/", pat)[:16])
    for w, pat in WEAK:
        if re.search(pat, s):
            pts += w
            why.append(re.sub(r"[|$\\s]", "/", pat)[:16])
    # 語数が多いほど具体的で、答えが1文で済みにくい
    if len(re.split(r"[\s　]+", s.strip())) >= 3:
        pts += 1
        why.append("+具体的")
    return pts, "・".join(why[:4]) or "手がかりなし"


def verdict(kw):
    p, why = score(kw)
    if p >= 2:
        return "強", p, why
    if p >= 0:
        return "並", p, why
    return "弱", p, why


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 0
    print("%-4s %4s  %-34s %s" % ("判定", "点", "検索語", "理由"))
    for kw in sys.argv[1:]:
        v, p, why = verdict(kw)
        print("%-4s %4d  %-34s %s" % (v, p, kw[:34], why))
    return 0


if __name__ == "__main__":
    sys.exit(main())
