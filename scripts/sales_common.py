def seg(say, head="", lines=None, bars=None, active="", unit="", **kw):
    """1区間。`kind` を渡すと video_slides の型で描かれる"""
    d = {"say": say, "head": head, "lines": lines or []}
    if bars:
        d["bars"] = bars
    if active:
        d["active"] = active
    if unit:
        d["unit"] = unit
    d.update(kw)
    return d


def part(num, eyebrow, big, notes, say):
    """章の扉。話の切り替わりを1枚で見せる"""
    return seg(say, kind="title", part=num, eyebrow=eyebrow, big=big, notes=notes)


MAX_SAY = 54


def expand(segments):
    """長い読み上げを、同じ絵のまま複数の区間に割る。

    **1区間が長いと、その間スライドが止まる。** 実測で25秒動かなかったことがある。
    句点、それでも長ければ読点で割り、絵はそのまま引き継ぐ。
    """
    import re
    out = []
    for s in segments:
        text = s["say"]
        if len(text) <= MAX_SAY:
            out.append(s)
            continue
        chunks = []
        for x in re.split(r"(?<=。)", text):
            x = x.strip()
            if not x:
                continue
            if len(x) <= MAX_SAY:
                chunks.append(x)
                continue
            cur = ""
            for p in re.split(r"(?<=、)", x):
                if len(cur) + len(p) > MAX_SAY and cur:
                    chunks.append(cur)
                    cur = p
                else:
                    cur += p
            if cur:
                chunks.append(cur)
        for c in chunks:
            out.append({**s, "say": c})
    return out
