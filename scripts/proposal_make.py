def tbl(head, rows, widths=None):
    w = widths or []
    th = "".join(f'<th{f" style=width:{x}" if x else ""}>{c}</th>'
                 for c, x in zip(head, w + [""] * len(head)))
    tr = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    return f"<table><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table>"


def cards(items):
    return '<div class="cards">' + "".join(
        f'<div class="card"><div class="ic">{"◆"}</div>'
        f'<div class="cn">{n}</div><div class="ct">{t}</div>'
        f'<div class="cb">{b}</div></div>' for n, t, b in items) + "</div>"


def bars(rows, unit=""):
    mx = max(v for _, v, _ in rows) or 1
    out = ['<div class="bars">']
    for label, v, note in rows:
        on = "on" if note == "★" else ""
        out.append(
            f'<div class="bar {on}"><div class="bl">{label}</div>'
            f'<div class="bt"><i style="width:{v / mx * 100:.0f}%"></i></div>'
            f'<div class="bv">{v}{unit}</div></div>')
    return "".join(out) + "</div>"


def flow(steps, note="", on=-1):
    """横に並ぶ工程図。矢印は「この順でしか進まない」ことを示す。

    on に番号を渡すと、その段だけ濃紺で塗る。いまどこの話かが一目で分かる
    （以前の提案書と同じ作法）。
    """
    items = []
    for i, (t, b) in enumerate(steps):
        if i:
            items.append('<div class="fa">&rarr;</div>')
        cls = "fs on" if i == on else "fs"
        items.append(f'<div class="{cls}"><div class="ft"><i>{i + 1}</i>{t}</div>'
                     f'<div class="fb">{b}</div></div>')
    out = '<div class="flow">' + "".join(items) + "</div>"
    return out + (f'<p class="note">{note}</p>' if note else "")


def sub(title, paras):
    """補足の解説。**表と図だけでは伝わらない「なぜ」をここで書く。**

    商談では読み上げず、持ち帰って読まれる部分。ここが薄いと、
    社内で検討されるときに根拠が伝わらない。
    """
    body = "".join(f"<p>{x}</p>" for x in paras)
    return f'<div class="sub"><h4>{title}</h4>{body}</div>'


def flist(groups):
    """機能の一覧。**1行1機能、説明は1文まで。**

    表で組むと機能名の列が間延びするので、名前と説明を縦に重ねた札にする。
    A4横に3列×多段で入る。
    """
    out = []
    for gname, gnote, items in groups:
        out.append(f'<div class="fg"><div class="fgh"><b>{gname}</b>'
                   f'<span>{gnote}</span></div><div class="fgl">')
        for name, desc in items:
            out.append(f'<div class="fi"><div class="fin">{name}</div>'
                       f'<div class="fid">{desc}</div></div>')
        out.append("</div></div>")
    return '<div class="flist">' + "".join(out) + "</div>"


def deep(paras, note=""):
    """補足だけの1ページ。2段組で読ませる。

    商談では読み上げない。持ち帰って社内で検討されるときに、
    「なぜそうするのか」がここだけで分かる状態にしておく。
    """
    body = "".join(f"<p>{x}</p>" for x in paras)
    # 段落が少ないページは文字を大きくする。2段組のまま小さい字だと、
    # 下半分が白く空いて「書きかけ」に見えるため。
    # 段落の切れ目も高さを食うので、字数だけで決めない
    # （字数が同じでも段落が多いページから先に溢れた）
    n = sum(len(re.sub("<[^>]+>", "", x)) for x in paras) + 60 * len(paras)
    tier = "big" if n < 1000 else ("mid" if n < 1250 else "")
    out = f'<div class="deep {tier}">{body}</div>'
    return out + (f'<p class="note">{note}</p>' if note else "")


