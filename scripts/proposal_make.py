def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--html", action="store_true", help="HTMLだけ作る")
    ap.add_argument("--industry", default="", help="業種名（industries.json の name。例: 歯科医院）で1ページ差し込む")
    a = ap.parse_args()

    f = facts()
    if a.industry:
        f["industry"] = industry_facts(a.industry)
        if not f["industry"]:
            raise SystemExit(f"業種が data/industries.json に無い、または記事が無い: {a.industry}")
    HTML.parent.mkdir(parents=True, exist_ok=True)
    HTML.write_text(html(f), encoding="utf-8")
    print(f"  HTML: {HTML}（{len(PAGES)}ページ）")
    if a.html:
        return 0

    from playwright.sync_api import sync_playwright
    out = OUT_DIR / (f"AIO提案書_{f['industry']['name']}向け.pdf" if f.get("industry") else "AIO提案書_詳細版.pdf")
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page()
        pg.goto(HTML.as_uri())
        pg.wait_for_timeout(500)
        # 1ページに収まらない章は、商談中にめくる位置がずれる。作る側で気づけるようにする
        over = pg.evaluate("""() => [...document.querySelectorAll('.p')].map((e,i)=>
            ({i:i+1, h:e.scrollHeight, t:(e.querySelector('h1')||{}).textContent||''}))
            .filter(x => x.h > 794)""")
        pg.pdf(path=str(out), width="297mm", height="210mm", print_background=True,
               margin={"top": "0", "bottom": "0", "left": "0", "right": "0"})
        b.close()
    for i, eye, dup in dup_check():
        print(f'  段落の重複: {i}ページ「{eye}」 {len(dup)}件 … {dup[0]}…')
    for x in over:
        print(f'  ページ溢れ: {x["i"]}ページ「{x["t"]}」 {x["h"]}px')
    print(f"  PDF: {out}（{out.stat().st_size / 1024 / 1024:.1f}MB）")
    return 0


