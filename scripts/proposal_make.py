def dup_check():
    """同じ段落が2回出ているページを出す。

    言い回しを変えて書き直しても、書き出しはたいてい残る。
    そこで**先頭22字**で突き合わせる。中身の一致ではなく、書き出しの一致を見る。
    """
    bad = []
    for i, pg in enumerate(PAGES, 1):
        seen, dup = set(), []
        for x in re.findall(r"<p[^>]*>(.*?)</p>", pg["body"], re.S):
            k = re.sub("<[^>]+>", "", x).strip()[:22]
            if len(k) < 12:
                continue
            if k in seen:
                dup.append(k)
            seen.add(k)
        if dup:
            bad.append((i, pg["eyebrow"], dup))
    return bad


